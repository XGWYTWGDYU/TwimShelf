    static Dictionary<string, string> T => All.GetValueOrDefault(Services.L10n.TagFor(System.Globalization.CultureInfo.CurrentUICulture.Name)) ?? All["en"];

    /// A text, its %s filled in order.
    public static string S(string key, params object[] args)
    {
        var s = T.GetValueOrDefault(key) ?? All["en"][key];
        foreach (var a in args) { var i = s.IndexOf("%s", StringComparison.Ordinal); if (i >= 0) s = s[..i] + a + s[(i + 2)..]; }
        return s;
    }
