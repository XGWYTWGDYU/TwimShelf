#!/usr/bin/env python3
"""TypeScript types of the core's JSON, generated from the Dart models.

  python3 scripts/gen_web_models.py           write web/packages/core/src/generated/models.ts
  python3 scripts/gen_web_models.py --check   fail when it is out of date

`flutter/tl_core/lib/src/models.dart` mirrors the Rust core's serde types (snake_case keys). The
React front end reads the same JSON, so its types come from there: each enum becomes a union of its
wire values, each class an interface of its `final` fields. Fields the Dart side derives itself
(not read from the JSON) are left out where listed in SKIP.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "flutter/tl_core/lib/src/models.dart"
OUT = ROOT / "web/packages/core/src/generated/models.ts"
# FeedItem's width/height come from the JSON's `size` pair
SKIP = {("FeedItem", "width"), ("FeedItem", "height")}
EXTRA = {"FeedItem": ["  /** [width, height] as displayed; absent until read from the file. */", "  size?: [number, number] | null;"]}


def ts(t, enums, classes):
    t = t.strip()
    opt = t.endswith("?")
    t = t.rstrip("?")
    m = re.fullmatch(r"List<(.+)>", t)
    if m:
        inner = ts(m.group(1), enums, classes)
        base = f"({inner})[]" if "|" in inner else f"{inner}[]"
    elif m := re.fullmatch(r"Map<String,\s*(.+)>", t):
        base = f"Record<string, {ts(m.group(1), enums, classes)}>"
    else:
        base = {"String": "string", "int": "number", "double": "number", "num": "number", "bool": "boolean",
                "dynamic": "unknown", "Object": "unknown"}.get(t)
        if base is None:
            base = t if t in enums or t in classes else "unknown"
    return f"{base} | null" if opt else base


def main():
    text = SRC.read_text(encoding="utf-8")
    enums = {}
    for name, body in re.findall(r"^enum (\w+) \{(.*?)^\}", text, re.S | re.M):
        enums[name] = re.findall(r"^\s*\w+\('([^']*)'\)", body, re.M)
    blocks = re.split(r"^(?=(?:sealed |final |abstract interface )?class )", text, flags=re.M)
    classes = {}
    for b in blocks:
        m = re.match(r"(?:sealed |final |abstract interface )?class (\w+)", b)
        if not m:
            continue
        fields = []
        for doc, typ, names in re.findall(r"((?:^\s*///.*\n)*)^\s*final ((?:\w+<[\w<>?, ]+>|\w+)\??) ([\w, ]+);", b, re.M):
            for name in (n.strip() for n in names.split(",")):
                if (m.group(1), name) not in SKIP:
                    fields.append((doc, typ, name))
        classes[m.group(1)] = fields
    lines = ["// GENERATED by scripts/gen_web_models.py from flutter/tl_core/lib/src/models.dart: do not edit.",
             "// The core's JSON (Rust serde, snake_case keys)."]
    for name, values in enums.items():
        lines.append("")
        lines.append(f"export type {name} = {' | '.join(repr(v) for v in values)};")
    for name, fields in classes.items():
        if name == "JsonModel":
            continue
        lines.append("")
        lines.append(f"export interface {name} {{")
        for doc, typ, field in fields:
            for d in doc.strip().splitlines():
                lines.append("  /** " + d.strip().lstrip("/").strip() + " */")
            t = ts(typ, enums, classes)
            q = "?" if "null" in t else ""
            lines.append(f"  {field}{q}: {t};")
        lines += EXTRA.get(name, [])
        lines.append("}")
    out = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != out:
            raise SystemExit("out of date (run scripts/gen_web_models.py): " + str(OUT.relative_to(ROOT)))
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8")
    print(f"{len(enums)} enums, {len(classes) - 1} interfaces")


if __name__ == "__main__":
    main()
