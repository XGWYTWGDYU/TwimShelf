#!/usr/bin/env python3
"""The Windows app's P/Invoke declarations, from the core's C header.

Apple/Shared/tl_core.h is the one list of what the core exports (the Swift apps import it as
it is). This writes windows/TwimShelf/Core/Native.g.cs from it, so the Windows app never keeps a
second, hand-written copy:

    python3 scripts/windows_bindings.py           write the file
    python3 scripts/windows_bindings.py --check   fail when it is out of date (CI)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "Apple" / "Shared" / "tl_core.h"
OUT = ROOT / "windows" / "TwimShelf" / "Core" / "Native.g.cs"

# C type -> (C# parameter type, C# return type, attribute for bool)
SCALARS = {
    "void": "void",
    "bool": "bool",
    "uint8_t": "byte",
    "uint16_t": "ushort",
    "int32_t": "int",
    "uint32_t": "uint",
    "int64_t": "long",
    "uint64_t": "ulong",
    "double": "double",
}

# what only the Apple apps call (it takes C function pointers, which this file does not declare)
APPLE_ONLY = {"tl_ai_set_mlx"}
DECL = re.compile(r"^\s*([A-Za-z_][\w ]*?\s*\**)\s*\b(tl_\w+)\s*\(([^)]*)\)\s*;")


def cs_type(c, position):
    """position: 'param' or 'return'."""
    c = " ".join(c.replace("*", " * ").split())
    if c == "const char *":
        return "string?" if position == "param" else None
    if c == "char *":
        # returned strings are the core's (freed with tl_string_free); the one parameter that
        # takes such a string back is tl_string_free itself
        return "nint"
    if c.endswith("*"):
        base = c[:-1].strip()
        if base in ("TlGrid", "TlPet"):
            return "nint"
        if base in SCALARS:
            return SCALARS[base] + "*"
        raise SystemExit(f"unknown pointer type: {c}")
    if c in SCALARS:
        return SCALARS[c]
    raise SystemExit(f"unknown type: {c}")


def generate():
    lines = []
    for raw in HEADER.read_text(encoding="utf-8").splitlines():
        m = DECL.match(raw)
        if not m:
            continue
        ret, name, params = m.groups()
        if name in APPLE_ONLY:
            continue
        rtype = cs_type(ret, "return")
        args = []
        params = params.strip()
        if params and params != "void":
            for i, p in enumerate(params.split(",")):
                p = p.strip()
                pm = re.match(r"(.*?)(\w+)$", p)
                ptype, pname = pm.group(1).strip(), pm.group(2)
                t = cs_type(ptype, "param")
                attr = "[MarshalAs(UnmanagedType.U1)] " if t == "bool" else ""
                args.append(f"{attr}{t} @{pname}")
        rattr = "    [return: MarshalAs(UnmanagedType.U1)]\n" if rtype == "bool" else ""
        lines.append(f"    [LibraryImport(Lib, StringMarshalling = StringMarshalling.Utf8)]\n{rattr}"
                     f"    internal static partial {rtype} {name}({', '.join(args)});")
    body = "\n\n".join(lines)
    return (
        "// <auto-generated>\n"
        "// Made by scripts/windows_bindings.py from Apple/Shared/tl_core.h: do not edit.\n"
        "// </auto-generated>\n"
        "#nullable enable\nusing System.Runtime.InteropServices;\n\n"
        "namespace TwimShelf.Core;\n\n"
        "internal static unsafe partial class Native\n{\n"
        "    private const string Lib = \"tl_core\";\n\n"
        f"{body}\n}}\n"
    )


def main():
    text = generate()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            raise SystemExit(f"{OUT.relative_to(ROOT)} is out of date: run python3 scripts/windows_bindings.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
