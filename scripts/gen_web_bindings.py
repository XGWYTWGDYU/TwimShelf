#!/usr/bin/env python3
"""The web front end's view of the core, generated from the FFI declarations.

  python3 scripts/gen_web_bindings.py           write both files
  python3 scripts/gen_web_bindings.py --check   fail when they are out of date

The Flutter app reaches the Rust core through `flutter/tl_core/lib/src/bindings.dart` (C ABI,
`dart:ffi`). A browser has no FFI, so the web build calls the same functions over HTTP on the
TwimShelf server (`server/`), one request per call, arguments and result as JSON. Both sides are
generated from the one declaration list so they cannot drift apart:

  flutter/tl_core/lib/src/bindings_web.dart   CoreBindings with the same method names, for the web
  server/src/dispatch.rs                      the server's table: name -> the core's C function

Only functions whose arguments and result are strings, whole numbers or booleans cross the wire.
The photo grid's and the mascot's engines (`tl_grid_*`, `tl_pet_*`) are per-frame and work on
native handles: the web build has its own (`grid_web.dart`, `pet_web.dart`).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BINDINGS = ROOT / "flutter/tl_core/lib/src/bindings.dart"
WEB = ROOT / "flutter/tl_core/lib/src/bindings_web.dart"
DISPATCH = ROOT / "server/src/dispatch.rs"

INT = {"Uint8": "u8", "Uint16": "u16", "Uint32": "u32", "Uint64": "u64", "Int32": "i32", "Int64": "i64"}


def declarations():
    text = BINDINGS.read_text(encoding="utf-8")
    out = []
    for name, sig, sym in re.findall(r"late final (\w+) =\s*library\s*\.lookupFunction<\s*(.*?)>\(\s*'(\w+)'\s*\);", text, re.S):
        sig = " ".join(sig.split())
        m = re.match(r"(\w+(?:<\w+>)?) Function\((.*?)\)\s*,", sig)
        if not m:
            raise SystemExit(f"cannot read the declaration of {name}: {sig}")
        ret, params = m.group(1), [p.strip() for p in m.group(2).split(",") if p.strip()]
        out.append((sym, ret, params))
    return out


def wire(ret, params):
    ok = lambda t: t == "Pointer<Utf8>" or t in INT or t == "Bool"
    return ok(ret) or ret == "Void" if all(ok(p) for p in params) else False


def dart_type(t):
    return "String?" if t == "Pointer<Utf8>" else "bool" if t == "Bool" else "int" if t in INT else None


def gen_dart(decls):
    lines = [
        "// GENERATED by scripts/gen_web_bindings.py from bindings.dart: do not edit.",
        "// The core's functions for the web build: the same names as the FFI bindings, each one a",
        "// call to the TwimShelf server (see web_transport.dart).",
        "import 'web_transport.dart';",
        "",
        "class CoreBindings {",
        "  CoreBindings();",
        "  /// Strings come back as Dart strings: nothing to free.",
        "  void tl_string_free(String? s) {}",
    ]
    for sym, ret, params in decls:
        if sym == "tl_string_free" or not wire(ret, params):
            continue
        args = ", ".join(f"{dart_type(p)} a{i}" for i, p in enumerate(params))
        call = f"coreCall('{sym}', [{', '.join(f'a{i}' for i in range(len(params)))}])"
        if ret == "Void":
            lines.append(f"  void {sym}({args}) {{ {call}; }}")
        elif ret == "Pointer<Utf8>":
            lines.append(f"  String? {sym}({args}) => {call} as String?;")
        elif ret == "Bool":
            lines.append(f"  bool {sym}({args}) => {call} == true;")
        else:
            lines.append(f"  int {sym}({args}) => ({call} as num).toInt();")
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_rust(decls):
    lines = [
        "// GENERATED by scripts/gen_web_bindings.py from flutter/tl_core/lib/src/bindings.dart: do not edit.",
        "//! The web build's calls: a function's name and its arguments (JSON) to the core's C function.",
        "use crate::wire::{Args, take};",
        "use serde_json::Value;",
        "use tl_core::ffi;",
        "",
        "/// Calls `name` with `args` (only names in `NAMES`).",
        "pub fn call(name: &str, args: &Args) -> anyhow::Result<Value> {",
        "    Ok(match name {",
    ]
    for sym, ret, params in decls:
        if sym == "tl_string_free" or not wire(ret, params):
            continue
        prep, passing = [], []
        for i, p in enumerate(params):
            if p == "Pointer<Utf8>":
                prep.append(f"let a{i} = args.c_str({i})?;")
                passing.append(f"args.ptr(&a{i})")
            elif p == "Bool":
                passing.append(f"args.bool({i})?")
            else:
                passing.append(f"args.int::<{INT[p]}>({i})?")
        invoke = f"ffi::{sym}({', '.join(passing)})"
        if ret == "Void":
            body = f"{{ {' '.join(prep)} {invoke}; Value::Null }}"
        elif ret == "Pointer<Utf8>":
            body = f"{{ {' '.join(prep)} take({invoke}) }}"
        else:
            body = f"{{ {' '.join(prep)} Value::from({invoke}) }}"
        lines.append(f"        \"{sym}\" => {body},")
    lines += [
        "        _ => anyhow::bail!(\"no such function: {name}\"),",
        "    })",
        "}",
        "",
        "/// Every function the web build may call.",
        "pub const NAMES: &[&str] = &[",
    ]
    for sym, ret, params in decls:
        if sym != "tl_string_free" and wire(ret, params):
            lines.append(f"    \"{sym}\",")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    decls = declarations()
    outputs = {WEB: gen_dart(decls), DISPATCH: gen_rust(decls)}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            raise SystemExit("out of date (run scripts/gen_web_bindings.py): " + ", ".join(stale))
        return
    for p, t in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t, encoding="utf-8")
    n = sum(1 for s, r, p in decls if s != "tl_string_free" and wire(r, p))
    print(f"{n} functions over the wire, {len(decls) - n - 1} native only")


if __name__ == "__main__":
    main()
